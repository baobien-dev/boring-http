import re
from datetime import UTC, datetime
from http import HTTPStatus
from http.client import HTTPSConnection
from pathlib import Path


class Source:
    HOST = "www.rfc-editor.org"
    PATH = "/rfc/rfc7541.txt"
    STATIC_HEADING = "Appendix A.  Static Table Definition"
    HUFFMAN_HEADING = "Appendix B.  Huffman Code"
    STATIC_ENTRIES = 61
    SYMBOLS = 257


class HpackTablesGenerator:
    # one row of the static table: | index | name | value |
    STATIC_ROW = re.compile(r"\s*\|\s*(\d+)\s*\|\s*(\S+)\s*\|\s*(.*?)\s*\|\s*$")
    # one row of the Huffman table: symbol ( code ) |bits  hex  [ length ]
    HUFFMAN_ROW = re.compile(r"\(\s*(\d+)\)\s+\|([01|]+)\s+([0-9a-f]+)\s+\[\s*(\d+)\]")

    def __init__(self) -> None:
        self.output = Path(__file__).resolve().parents[1] / "src" / "boring_http" / "hpack_tables.py"

    def run(self) -> None:
        text = self.download()
        static = self.static_table(text[text.index(Source.STATIC_HEADING) : text.index(Source.HUFFMAN_HEADING)])
        huffman = self.huffman_codes(text[text.index(Source.HUFFMAN_HEADING) :])
        today = datetime.now(UTC).date().isoformat()
        lines = [
            f"# Generated by tools/generate_hpack_tables.py from RFC 7541 appendices A and B, downloaded {today}.",
            "# Regenerate rather than edit.",
            "",
            "",
            "class HpackTables:",
            "    # the 61 static entries, index 1 first",
            "    STATIC: tuple[tuple[bytes, bytes], ...] = (",
        ]
        lines += [f"        ({self.literal(name)}, {self.literal(value)})," for name, value in static]
        lines += [
            "    )",
            "    # the Huffman code of every byte value and of EOS, as (code, bit length)",
            "    HUFFMAN: tuple[tuple[int, int], ...] = (",
        ]
        lines += [f"        (0x{code:X}, {length})," for code, length in huffman]
        lines += ["    )", ""]
        self.output.write_text("\n".join(lines))
        print(self.output, f"static={len(static)} huffman={len(huffman)}")

    @staticmethod
    def download() -> str:
        connection = HTTPSConnection(Source.HOST)
        try:
            connection.request("GET", Source.PATH, headers={"User-Agent": "boring-http tools/generate_hpack_tables"})
            response = connection.getresponse()
            body = response.read()
        finally:
            connection.close()
        if response.status != HTTPStatus.OK:
            raise RuntimeError(f"https://{Source.HOST}{Source.PATH} answered {response.status}")
        return body.decode()

    @staticmethod
    def literal(value: bytes) -> str:
        # the table holds plain ASCII header names and values, so a double-quoted bytes literal needs no escaping
        text = value.decode("ascii")
        if '"' in text or "\\" in text:
            raise ValueError(f"{value!r} needs escaping")
        return f'b"{text}"'

    def static_table(self, text: str) -> list[tuple[bytes, bytes]]:
        entries: dict[int, tuple[bytes, bytes]] = {}
        for line in text.splitlines():
            if match := self.STATIC_ROW.match(line):
                entries[int(match[1])] = (match[2].encode(), match[3].encode())
        if sorted(entries) != list(range(1, Source.STATIC_ENTRIES + 1)):
            raise ValueError(f"the static table has {len(entries)} rows, not {Source.STATIC_ENTRIES}")
        return [entries[index] for index in range(1, Source.STATIC_ENTRIES + 1)]

    def huffman_codes(self, text: str) -> list[tuple[int, int]]:
        codes: dict[int, tuple[int, int]] = {}
        for line in text.splitlines():
            if match := self.HUFFMAN_ROW.search(line):
                symbol, bits, code, length = int(match[1]), match[2].replace("|", ""), int(match[3], 16), int(match[4])
                if len(bits) != length or int(bits, 2) != code:
                    raise ValueError(f"the bits and the hex code of symbol {symbol} disagree")
                codes[symbol] = (code, length)
        if sorted(codes) != list(range(Source.SYMBOLS)):
            raise ValueError(f"the Huffman table has {len(codes)} symbols, not {Source.SYMBOLS}")
        return [codes[symbol] for symbol in range(Source.SYMBOLS)]


if __name__ == "__main__":
    HpackTablesGenerator().run()
