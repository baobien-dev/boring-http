import re
from http import HTTPStatus
from http.client import HTTPSConnection
from pathlib import Path


class Source:
    HOST = "publicsuffix.org"
    PATH = "/list/public_suffix_list.dat"
    ICANN_BEGIN = "// ===BEGIN ICANN DOMAINS==="
    PRIVATE_BEGIN = "// ===BEGIN PRIVATE DOMAINS==="
    COMMENT = "//"
    EXCEPTION = "!"
    WILDCARD = "*."
    LEAST_RULES = 9000


class PublicSuffixesGenerator:
    VERSION = re.compile(r"^// VERSION: (\S+)$", re.MULTILINE)
    COMMIT = re.compile(r"^// COMMIT: (\S+)$", re.MULTILINE)
    RULE = re.compile(r"(\*\.)?[a-z0-9-]+(\.[a-z0-9-]+)*")

    def __init__(self) -> None:
        self.output = Path(__file__).resolve().parents[1] / "src" / "boring_http" / "public_suffixes.py"

    def run(self) -> None:
        text = self.download()
        version, commit = self.VERSION.search(text), self.COMMIT.search(text)
        if version is None or commit is None or Source.ICANN_BEGIN not in text or Source.PRIVATE_BEGIN not in text:
            raise ValueError("the list has lost its VERSION, COMMIT or section markers")
        rules: set[str] = set()
        exceptions: set[str] = set()
        for line in text.splitlines():
            rule = line.strip().split(" ")[0].lower()
            if not rule or rule.startswith(Source.COMMENT):
                continue
            target = exceptions if rule.startswith(Source.EXCEPTION) else rules
            target.add(".".join(self.ascii_label(label) for label in rule.removeprefix(Source.EXCEPTION).split(".")))
        if len(rules) < Source.LEAST_RULES or not exceptions:
            raise ValueError(f"{len(rules)} rules and {len(exceptions)} exceptions is not the Public Suffix List")
        for rule in rules | exceptions:
            if not self.RULE.fullmatch(rule):
                raise ValueError(f"{rule!r} is not a rule")
        lines = [
            f"# Generated by tools/generate_public_suffixes.py from the Public Suffix List {version[1]}, commit {commit[1]}.",
            "# The list is published by publicsuffix.org under the Mozilla Public License 2.0, https://mozilla.org/MPL/2.0/.",
            "# Regenerate rather than edit.",
            "",
            "",
            "class PublicSuffixes:",
            "    # every rule, wildcards as *.parent, labels in ASCII",
            "    RULES = frozenset(",
            "        {",
        ]
        lines += [f'            "{rule}",' for rule in sorted(rules)]
        lines += [
            "        }",
            "    )",
            "    # the exception rules, without their leading !",
            "    EXCEPTIONS = frozenset(",
            "        {",
        ]
        lines += [f'            "{rule}",' for rule in sorted(exceptions)]
        lines += ["        }", "    )", ""]
        self.output.write_text("\n".join(lines))
        print(self.output, f"rules={len(rules)} exceptions={len(exceptions)} version={version[1]}")

    @staticmethod
    def download() -> str:
        connection = HTTPSConnection(Source.HOST)
        try:
            connection.request("GET", Source.PATH, headers={"User-Agent": "boring-http tools/generate_public_suffixes"})
            response = connection.getresponse()
            body = response.read()
        finally:
            connection.close()
        if response.status != HTTPStatus.OK:
            raise RuntimeError(f"https://{Source.HOST}{Source.PATH} answered {response.status}")
        return body.decode()

    @staticmethod
    def ascii_label(label: str) -> str:
        return label if label.isascii() else label.encode("idna").decode("ascii")


if __name__ == "__main__":
    PublicSuffixesGenerator().run()
