import re
from datetime import UTC, datetime
from http import HTTPStatus
from http.client import HTTPSConnection
from pathlib import Path


class Source:
    HOST = "www.rfc-editor.org"
    PATH = "/rfc/rfc9204.txt"
    HEADING = "Appendix A.  Static Table"
    ENTRIES = 99


class QpackTableGenerator:
    # one row of the static table: | index | name | value |
    ROW = re.compile(r"\s*\|\s*(\d+)\s*\|\s*(\S+)\s*\|\s*(.*?)\s*\|\s*$")

    def __init__(self) -> None:
        self.output = Path(__file__).resolve().parents[1] / "src" / "boring_http" / "qpack_tables.py"

    def run(self) -> None:
        text = self.download()
        entries = self.static_table(text[text.rindex(Source.HEADING) :])
        today = datetime.now(UTC).date().isoformat()
        lines = [
            f"# Generated by tools/generate_qpack_table.py from RFC 9204 appendix A, downloaded {today}.",
            "# Regenerate rather than edit.",
            "",
            "",
            "class QpackTables:",
            "    # the 99 static entries, index 0 first",
            "    STATIC: tuple[tuple[bytes, bytes], ...] = (",
        ]
        lines += [f"        ({self.literal(name)}, {self.literal(value)})," for name, value in entries]
        lines += ["    )", ""]
        self.output.write_text("\n".join(lines))
        print(self.output, f"static={len(entries)}")

    @staticmethod
    def download() -> str:
        connection = HTTPSConnection(Source.HOST)
        try:
            connection.request("GET", Source.PATH, headers={"User-Agent": "boring-http tools/generate_qpack_table"})
            response = connection.getresponse()
            body = response.read()
        finally:
            connection.close()
        if response.status != HTTPStatus.OK:
            raise RuntimeError(f"https://{Source.HOST}{Source.PATH} answered {response.status}")
        return body.decode()

    @staticmethod
    def literal(value: bytes) -> str:
        # the table holds plain ASCII header names and values, so a double-quoted bytes literal needs no escaping
        text = value.decode("ascii")
        if '"' in text or "\\" in text:
            raise ValueError(f"{value!r} needs escaping")
        return f'b"{text}"'

    def static_table(self, text: str) -> list[tuple[bytes, bytes]]:
        entries: dict[int, tuple[bytes, bytes]] = {}
        for line in text.splitlines():
            if match := self.ROW.match(line):
                entries[int(match[1])] = (match[2].encode(), match[3].encode())
        if sorted(entries) != list(range(Source.ENTRIES)):
            raise ValueError(f"the static table has {len(entries)} rows, not {Source.ENTRIES}")
        return [entries[index] for index in range(Source.ENTRIES)]


if __name__ == "__main__":
    QpackTableGenerator().run()
